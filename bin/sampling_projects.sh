#!/bin/sh
#
# Creates (or refreshes) the `-s<n>' twin of a project: the same genomes under the same taxonomy,
# with only one k-mer in n entered into the database.
#
# What the twin is for. Kraken 2 does not store a k-mer at all. It stores a 32-bit cell per
# minimizer, 17 bits of truncated MurmurHash3 and 15 bits of taxon index, and it enters only the
# minimizers -- one ℓ-mer per k-mer window, which for its defaults k = 35 and l = 31 is a window of
# five and therefore a density of 2/(5+1) = 1/3. Genestrip enters every k-mer and stores it exactly:
# a 64-bit word holding 2k-r bits of the k-mer, 18 bits of value index and the mark bit, plus a
# 10-bit-per-entry Bloom filter in front of it. Measured on `cv' that is 8.72 bytes per entry on disk
# against 5.71 for Kraken 2, i.e. a factor of 1.53 that no sampling rate can change.
#
# So a database of Kraken 2's size needs 1.53 / (1/3) = 4.6 times coarser sampling than Kraken 2's
# own, which is what `kMerSampling' sets. The twin says what that costs, on the same genomes and the
# same read sets, with everything else held fixed.
#
# The mechanics are the ones of bin/k24_projects.sh, which explains them: the original's inputs by
# symlink, a config.properties generated from the original's with the one line that differs, and the
# fastq maps linked under the twin's name so that the twin is scored on the very read files the
# original was scored on. Re-running is safe and regenerates the config.
#
# Note that `kMerSampling' selects by the k-mer and not by its position -- KMerSampling.java does it
# with a multiplicative threshold, `kmer * 0x9E3779B97F4A7C15' unsigned against `(2^64-1)/n'. That is
# what keeps the tax ids right: a k-mer is entered in every genome it occurs in or in none of them,
# whereas selecting by position would miss an occurrence and leave the k-mer looking more specific
# than it is.
#
# Usage: sh ./bin/sampling_projects.sh [project ...]     (default: viral)
#
# Environment:
#   S   one k-mer in how many to enter, default 4. It names the twin as well, so S=5 writes
#       `viral-s5'. Genestrip's kMerSampling takes 1 or more; 1 would make the twin a copy of the
#       original.
#   K   a k-mer length to set along with the sampling, unset by default, which leaves Genestrip's
#       own 31. K=24 writes `viral-k24-s4' and sets both keys, so that the two ways of making the
#       database smaller can be measured together: the seed weight of bin/k24_exps.sh and the
#       sampling of this one. The twin is built from the original either way, never from the
#       `-k24' twin, so one project holds one complete configuration.
#
set -e

scriptdir=$(dirname "$0")
cd "$scriptdir/.."
basedir=$(pwd)
projdir="${basedir}/data/projects"
fqdir="${basedir}/data/fastq"

s=${S:-4}
case "$s" in
  ''|*[!0-9]*) echo "S must be a number, not '${s}'." >&2; exit 1 ;;
esac
if [ "$s" -lt 2 ]; then
  echo "S must be 2 or more - S=1 enters every k-mer and would copy the original." >&2
  exit 1
fi

# The k-mer length, and the part of the twin's name that says so. Empty leaves the default of 31 and
# the name without a `-k' part, which is what the reported `viral-s4' is.
k=${K:-}
ksuffix=""
if [ -n "$k" ]; then
  case "$k" in
    ''|*[!0-9]*) echo "K must be a number, not '${k}'." >&2; exit 1 ;;
  esac
  if [ "$k" -lt 15 ] || [ "$k" -gt 31 ]; then
    echo "K must be between 15 and 31 - Genestrip's kMerSize takes no other value." >&2
    exit 1
  fi
  ksuffix="-k${k}"
fi

if [ $# -gt 0 ]; then
  projects="$*"
else
  projects="viral"
fi

for p in $projects; do
  src="${projdir}/${p}"
  dst="${projdir}/${p}${ksuffix}-s${s}"
  if [ ! -d "$src" ]; then
    echo "No such project: ${src}" >&2
    exit 1
  fi
  mkdir -p "$dst"

  for f in "$src"/*; do
    [ -f "$f" ] || continue
    name=$(basename "$f")
    [ "$name" = "config.properties" ] && continue
    ln -sfn "../${p}/${name}" "${dst}/${name}"
  done

  {
    echo "# GENERATED by bin/sampling_projects.sh from ../${p}/config.properties -- do not edit."
    echo "#"
    echo "# The twin of \`${p}' that enters one k-mer in ${s} instead of every one of them, so that a"
    echo "# database of roughly the size Kraken 2 builds from the same genomes can be measured on the"
    if [ -n "$k" ]; then
      echo "# same read sets, and that matches Kraken 2's seed weight as well by shortening the k-mer"
      echo "# to ${k}. Everything below is the original project's configuration; the last two lines are"
      echo "# what makes the difference."
    else
      echo "# same read sets. Everything below is the original project's configuration; the last line is"
      echo "# what makes the difference."
    fi
    echo "#"
    if [ -f "${src}/config.properties" ]; then
      cat "${src}/config.properties"
      echo
    fi
    [ -n "$k" ] && echo "kMerSize=${k}"
    echo "kMerSampling=${s}"
  } > "${dst}/config.properties"

  for suffix in _sim.txt _sim_perfect.txt _sim_saliva.txt; do
    if [ -f "${fqdir}/${p}${suffix}" ]; then
      ln -sfn "${p}${suffix}" "${fqdir}/${p}${ksuffix}-s${s}${suffix}"
    else
      echo "  note: ${fqdir}/${p}${suffix} is not there yet - no map linked for it." >&2
    fi
  done

  echo "OK    ${dst} (${k:+kMerSize=${k}, }kMerSampling=${s}, $(ls -1 "$dst" | wc -l | tr -d ' ') entries)"
done
