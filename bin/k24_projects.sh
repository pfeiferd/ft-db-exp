#!/bin/sh
#
# Creates (or refreshes) the `-k24' twin of a project: the same genomes under the same taxonomy,
# built at a shorter k-mer length.
#
# What the twin is for. Kraken 2 classifies with a spaced seed of weight 24 -- 31 minimizer
# positions of which 7 are masked -- while Genestrip matches exact 31-mers. A seed's weight is the
# number of positions that must agree, and it is what decides both the error tolerance and how many
# k-mers two related species share, so a Genestrip database at k = 24 sits on the same point of that
# trade-off as Kraken 2's default. It is the one knob that moves the share of k-mers above the data
# taxa without touching the genomes, the read sets or the measures, which is what makes it a control
# for the question of what governs the refinement's gain.
#
# Everything but the k-mer length is shared: taxids.txt, additional.txt and categories.txt are
# symlinks to the original project, so the two cannot drift apart, and the genomes and the taxonomy
# live in data/common either way. The fastq mapping files are symlinked as well, under the twin's
# own name, so that the twin is evaluated on exactly the reads the original was evaluated on rather
# than on a second simulation of them.
#
# The name is what keeps the two apart on disk: data/projects/viral-k24/db/viral-k24_db.zip beside
# data/projects/viral/db/viral_db.zip, and results named after the project throughout.
#
# Re-running is safe and is the point: the config file is regenerated from the original's every
# time, so a setting added to `viral' reaches `viral-k24' the next time this runs.
#
# Usage: sh ./bin/k24_projects.sh [project ...]     (default: viral)
#
# Environment:
#   K   the k-mer length of the twin, default 24. It names the twin as well, so K=27 writes
#       `viral-k27'. Genestrip accepts 15 to 31; 31 would make the twin a copy of the original.
#
set -e

scriptdir=$(dirname "$0")
cd "$scriptdir/.."
basedir=$(pwd)
projdir="${basedir}/data/projects"
fqdir="${basedir}/data/fastq"

k=${K:-24}
case "$k" in
  ''|*[!0-9]*) echo "K must be a number, not '${k}'." >&2; exit 1 ;;
esac
if [ "$k" -lt 15 ] || [ "$k" -gt 31 ]; then
  echo "K must be between 15 and 31 - Genestrip's kMerSize takes no other value." >&2
  exit 1
fi

if [ $# -gt 0 ]; then
  projects="$*"
else
  projects="viral"
fi

for p in $projects; do
  src="${projdir}/${p}"
  dst="${projdir}/${p}-k${k}"
  if [ ! -d "$src" ]; then
    echo "No such project: ${src}" >&2
    exit 1
  fi
  mkdir -p "$dst"

  # Every input of the original, by symlink. A copy would be a second thing to maintain, and the
  # experiment is only worth anything if both databases are built from exactly the same definition.
  for f in "$src"/*; do
    [ -f "$f" ] || continue
    name=$(basename "$f")
    [ "$name" = "config.properties" ] && continue
    ln -sfn "../${p}/${name}" "${dst}/${name}"
  done

  # The one file that differs, and it is generated rather than maintained.
  {
    echo "# GENERATED by bin/k24_projects.sh from ../${p}/config.properties -- do not edit."
    echo "#"
    echo "# The twin of \`${p}' built at k = ${k} instead of Genestrip's default of 31, so that the"
    echo "# effect of the k-mer length on the refinement can be measured on one database with"
    echo "# everything else held fixed. Everything below is the original project's configuration;"
    echo "# the last line is what makes the difference."
    echo "#"
    if [ -f "${src}/config.properties" ]; then
      cat "${src}/config.properties"
      echo
    fi
    echo "kMerSize=${k}"
  } > "${dst}/config.properties"

  # The fastq mapping files, under the twin's name. run_classification_exps.sh derives the name of
  # a map from the project name -- <project>_sim.txt and so on -- so without these the twin would
  # have no read sets at all; with them it is scored on the very files the original was scored on,
  # which is what makes the two rows comparable. A map that is not there yet is skipped rather than
  # symlinked into nothing: `<p>_sim_saliva.txt' is written by make_fastqs.sh under ERROR_SALIVA=1
  # and may legitimately come later.
  for suffix in _sim.txt _sim_perfect.txt _sim_saliva.txt; do
    if [ -f "${fqdir}/${p}${suffix}" ]; then
      ln -sfn "${p}${suffix}" "${fqdir}/${p}-k${k}${suffix}"
    else
      echo "  note: ${fqdir}/${p}${suffix} is not there yet - no map linked for it." >&2
    fi
  done

  echo "OK    ${dst} (kMerSize=${k}, $(ls -1 "$dst" | wc -l | tr -d ' ') entries)"
done
