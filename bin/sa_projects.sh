#!/bin/sh
#
# Creates (or refreshes) the `-sa' twin of every project the classification performance scenarios
# measure: `viral-sa', `tick-borne-sa' and `strepto-sa'.
#
# A twin is the same database from the same genomes, filled into the other k-mer store: its
# config.properties carries `sortedArrayStore=true', which makes `fill' use KMerSortedArray, the
# binary-search store Genestrip used before RadixKMerStore, instead of the default. Everything else
# is shared -- taxids.txt, additional.txt, categories.txt are symlinks to the original project, so
# the two cannot drift apart, and the genomes and the taxonomy live in data/common either way.
#
# The name is what keeps the two apart on disk: data/projects/viral-sa/db/viral-sa_db.zip beside
# data/projects/viral/db/viral_db.zip, and results named after the project throughout. Nothing else
# needed a switch for that.
#
# Re-running is safe and is the point: the config file is regenerated from the original's every time,
# so a setting added to `strepto' reaches `strepto-sa' the next time this runs.
#
# Usage: bin/sa_projects.sh [project ...]     (default: the three of the perf scenarios)
#
set -e

scriptdir=$(dirname "$0")
cd "$scriptdir/.."
basedir=$(pwd)
projdir="${basedir}/data/projects"

if [ $# -gt 0 ]; then
  projects="$*"
else
  projects="viral tick-borne strepto"
fi

for p in $projects; do
  src="${projdir}/${p}"
  dst="${projdir}/${p}-sa"
  if [ ! -d "$src" ]; then
    echo "No such project: ${src}" >&2
    exit 1
  fi
  mkdir -p "$dst"

  # Every input of the original, by symlink. A copy would be a second thing to maintain, and the
  # experiment is only worth anything if both stores are filled from exactly the same definition.
  for f in "$src"/*; do
    [ -f "$f" ] || continue
    name=$(basename "$f")
    [ "$name" = "config.properties" ] && continue
    ln -sfn "../${p}/${name}" "${dst}/${name}"
  done

  # The one file that differs, and it is generated rather than maintained.
  {
    echo "# GENERATED by bin/sa_projects.sh from ../${p}/config.properties -- do not edit."
    echo "#"
    echo "# The twin of \`${p}' that fills its database into KMerSortedArray instead of the default"
    echo "# RadixKMerStore, so that the two lookup paths can be measured on the same data. Everything"
    echo "# below is the original project's configuration; the last line is what makes the difference."
    echo "#"
    if [ -f "${src}/config.properties" ]; then
      cat "${src}/config.properties"
      echo
    fi
    echo "sortedArrayStore=true"
  } > "${dst}/config.properties"

  echo "OK    ${dst} ($(ls -1 "$dst" | wc -l | tr -d ' ') entries)"
done
